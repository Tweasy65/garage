export function yearOptions(): number[] {
  const end = new Date().getFullYear() + 1
  const years: number[] = []
  for (let year = end; year >= FIRST_CAR_YEAR; year -= 1) {
    years.push(year)
  }
  return years
}

export function modelsForMake(make: string): string[] {
  return US_MODELS[make] ?? []
}
